const aws = @import("aws");
const std = @import("std");

const Client = @import("client.zig").Client;
const CallOptions = @import("call_options.zig").CallOptions;
const parseErrorResponse = @import("errors.zig").parseErrorResponse;
const FilterDefinition = @import("filter_definition.zig").FilterDefinition;
const NotebookMetadata = @import("notebook_metadata.zig").NotebookMetadata;

pub const ListNotebookMetadataInput = struct {
    /// Search filter string.
    filters: ?FilterDefinition = null,

    /// Specifies the maximum number of results to return.
    max_results: ?i32 = null,

    /// A token generated by the Athena service that specifies where to continue
    /// pagination if a previous request was truncated.
    next_token: ?[]const u8 = null,

    /// The name of the Spark enabled workgroup to retrieve notebook metadata for.
    work_group: []const u8,

    pub const json_field_names = .{
        .filters = "Filters",
        .max_results = "MaxResults",
        .next_token = "NextToken",
        .work_group = "WorkGroup",
    };
};

pub const ListNotebookMetadataOutput = struct {
    /// A token generated by the Athena service that specifies where to continue
    /// pagination if a previous request was truncated. To obtain the next set of
    /// pages, pass in
    /// the `NextToken` from the response object of the previous page call.
    next_token: ?[]const u8 = null,

    /// The list of notebook metadata for the specified workgroup.
    notebook_metadata_list: ?[]const NotebookMetadata = null,

    pub const json_field_names = .{
        .next_token = "NextToken",
        .notebook_metadata_list = "NotebookMetadataList",
    };
};

pub fn execute(client: *Client, allocator: std.mem.Allocator, input: ListNotebookMetadataInput, options: CallOptions) !ListNotebookMetadataOutput {
    var arena = std.heap.ArenaAllocator.init(client.allocator);
    defer arena.deinit();
    const alloc = arena.allocator();

    var request = try serializeRequest(alloc, input, client.config);
    defer request.deinit(alloc);

    const creds = try client.config.credentials.getCredentials(client.allocator);
    try aws.signing.signRequest(alloc, client.config.io, &request, creds, client.config.region, "athena", client.config.http_client.clock_skew_offset);

    var response = try client.config.http_client.sendRequestWithOptions(&request, client.options);
    defer response.deinit();

    if (!response.isSuccess()) {
        if (options.diagnostic) |d| {
            d.* = try parseErrorResponse(client.allocator, response.body, response.status);
        }
        return error.ServiceError;
    }

    const result = try deserializeResponse(allocator, response.body, response.status, response.headers);
    return result;
}

fn serializeRequest(allocator: std.mem.Allocator, input: ListNotebookMetadataInput, config: *aws.Config) !aws.http.Request {
    const endpoint = try config.getEndpointForService("athena", "Athena", allocator);

    const ep = try aws.url.parseEndpoint(endpoint);

    const body = try aws.json.jsonStringify(input, allocator);

    var request = aws.http.Request.init(ep.host);
    request.method = .POST;
    request.path = "/";
    request.tls = ep.tls;
    request.port = ep.port;
    request.body = body;
    try request.headers.put(allocator, "Content-Type", "application/x-amz-json-1.1");
    try request.headers.put(allocator, "X-Amz-Target", "AmazonAthena.ListNotebookMetadata");

    return request;
}

fn deserializeResponse(allocator: std.mem.Allocator, body: []const u8, status: u16, headers: anytype) !ListNotebookMetadataOutput {
    _ = status;
    _ = headers;
    if (body.len == 0) return .{};
    return aws.json.parseJsonObject(ListNotebookMetadataOutput, body, allocator);
}
