const aws = @import("aws");
const std = @import("std");

const Client = @import("client.zig").Client;
const CallOptions = @import("call_options.zig").CallOptions;
const parseErrorResponse = @import("errors.zig").parseErrorResponse;
const RecommendationDiversityConfig = @import("recommendation_diversity_config.zig").RecommendationDiversityConfig;
const RecommendationMetadata = @import("recommendation_metadata.zig").RecommendationMetadata;
const Recommender = @import("recommender.zig").Recommender;
const Recommendation = @import("recommendation.zig").Recommendation;

pub const SearchRecommendationsInput = struct {
    /// A list of item IDs to rank for the user. Use this when you want to re-rank a
    /// specific set of items rather than getting recommendations from the full item
    /// catalog. Required for personalized-ranking use cases.
    candidate_ids: ?[]const []const u8 = null,

    /// The contextual metadata used to provide dynamic runtime information to
    /// tailor recommendations.
    context: ?[]const aws.map.StringMapEntry = null,

    /// Runtime diversity configuration for this request. Enables diversity-aware
    /// recommendations and optionally supplies values for placeholder-based
    /// diversity caps configured on the recommender.
    diversity: ?RecommendationDiversityConfig = null,

    /// The unique name of the domain.
    domain_name: []const u8,

    /// A searchable identifier of a customer profile. You can use a predefined key,
    /// such as
    /// `_profileId`, `_phone`, or `_email`, or a custom-defined key.
    key_name: []const u8,

    /// A list of key values. Provide one value for each field of the search key.
    key_values: []const []const u8,

    /// The maximum number of recommendations to return. The default value is 5.
    max_recommendations: ?i32 = null,

    /// Configuration for metadata to include in recommendation responses.
    metadata: ?RecommendationMetadata = null,

    /// The recommender used to generate the recommendations.
    recommender: Recommender,

    pub const json_field_names = .{
        .candidate_ids = "CandidateIds",
        .context = "Context",
        .diversity = "Diversity",
        .domain_name = "DomainName",
        .key_name = "KeyName",
        .key_values = "KeyValues",
        .max_recommendations = "MaxRecommendations",
        .metadata = "Metadata",
        .recommender = "Recommender",
    };
};

pub const SearchRecommendationsOutput = struct {
    /// The unique identifier of the profile for which to retrieve recommendations.
    profile_id: ?[]const u8 = null,

    /// List of recommendations generated by the recommender.
    recommendations: ?[]const Recommendation = null,

    pub const json_field_names = .{
        .profile_id = "ProfileId",
        .recommendations = "Recommendations",
    };
};

pub fn execute(client: *Client, allocator: std.mem.Allocator, input: SearchRecommendationsInput, options: CallOptions) !SearchRecommendationsOutput {
    var arena = std.heap.ArenaAllocator.init(client.allocator);
    defer arena.deinit();
    const alloc = arena.allocator();

    var request = try serializeRequest(alloc, input, client.config);
    defer request.deinit(alloc);

    const creds = try client.config.credentials.getCredentials(client.allocator);
    try aws.signing.signRequest(alloc, client.config.io, &request, creds, client.config.region, "profile", client.config.http_client.clock_skew_offset);

    var response = try client.config.http_client.sendRequestWithOptions(&request, client.options);
    defer response.deinit();

    if (!response.isSuccess()) {
        if (options.diagnostic) |d| {
            d.* = try parseErrorResponse(client.allocator, response.body, response.status);
        }
        return error.ServiceError;
    }

    const result = try deserializeResponse(allocator, response.body, response.status, response.headers);
    return result;
}

fn serializeRequest(allocator: std.mem.Allocator, input: SearchRecommendationsInput, config: *aws.Config) !aws.http.Request {
    const endpoint = try config.getEndpointForService("profile", "Customer Profiles", allocator);

    const ep = try aws.url.parseEndpoint(endpoint);

    var path_buf: std.ArrayList(u8) = .empty;
    try path_buf.appendSlice(allocator, "/domains/");
    try path_buf.appendSlice(allocator, input.domain_name);
    try path_buf.appendSlice(allocator, "/recommendations");
    const path = try path_buf.toOwnedSlice(allocator);

    var body_buf: std.ArrayList(u8) = .empty;
    var has_prev = false;
    try body_buf.appendSlice(allocator, "{");

    if (input.candidate_ids) |v| {
        if (has_prev) try body_buf.appendSlice(allocator, ",");
        try body_buf.appendSlice(allocator, "\"CandidateIds\":");
        try aws.json.writeValue(@TypeOf(v), v, allocator, &body_buf);
        has_prev = true;
    }
    if (input.context) |v| {
        if (has_prev) try body_buf.appendSlice(allocator, ",");
        try body_buf.appendSlice(allocator, "\"Context\":");
        try aws.json.writeValue(@TypeOf(v), v, allocator, &body_buf);
        has_prev = true;
    }
    if (input.diversity) |v| {
        if (has_prev) try body_buf.appendSlice(allocator, ",");
        try body_buf.appendSlice(allocator, "\"Diversity\":");
        try aws.json.writeValue(@TypeOf(v), v, allocator, &body_buf);
        has_prev = true;
    }
    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"KeyName\":");
    try aws.json.writeValue(@TypeOf(input.key_name), input.key_name, allocator, &body_buf);
    has_prev = true;
    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"KeyValues\":");
    try aws.json.writeValue(@TypeOf(input.key_values), input.key_values, allocator, &body_buf);
    has_prev = true;
    if (input.max_recommendations) |v| {
        if (has_prev) try body_buf.appendSlice(allocator, ",");
        try body_buf.appendSlice(allocator, "\"MaxRecommendations\":");
        try aws.json.writeValue(@TypeOf(v), v, allocator, &body_buf);
        has_prev = true;
    }
    if (input.metadata) |v| {
        if (has_prev) try body_buf.appendSlice(allocator, ",");
        try body_buf.appendSlice(allocator, "\"Metadata\":");
        try aws.json.writeValue(@TypeOf(v), v, allocator, &body_buf);
        has_prev = true;
    }
    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"Recommender\":");
    try aws.json.writeValue(@TypeOf(input.recommender), input.recommender, allocator, &body_buf);
    has_prev = true;

    try body_buf.appendSlice(allocator, "}");
    const body = try body_buf.toOwnedSlice(allocator);

    var request = aws.http.Request.init(ep.host);
    request.method = .POST;
    request.path = path;
    request.tls = ep.tls;
    request.port = ep.port;
    request.body = body;
    try request.headers.put(allocator, "Content-Type", "application/json");

    return request;
}

fn deserializeResponse(allocator: std.mem.Allocator, body: []const u8, status: u16, headers: anytype) !SearchRecommendationsOutput {
    const result: SearchRecommendationsOutput = try aws.json.parseJsonObject(
        SearchRecommendationsOutput,
        if (body.len > 0) body else "{}",
        allocator,
    );
    _ = status;
    _ = headers;

    return result;
}
