const aws = @import("aws");
const std = @import("std");

const Client = @import("client.zig").Client;
const CallOptions = @import("call_options.zig").CallOptions;
const parseErrorResponse = @import("errors.zig").parseErrorResponse;
const S3Location = @import("s3_location.zig").S3Location;
const TransformerJobStatus = @import("transformer_job_status.zig").TransformerJobStatus;

pub const GetTransformerJobInput = struct {
    /// Specifies the system-assigned unique identifier for the transformer.
    transformer_id: []const u8,

    /// Specifies the unique, system-generated identifier for a transformer run.
    transformer_job_id: []const u8,

    pub const json_field_names = .{
        .transformer_id = "transformerId",
        .transformer_job_id = "transformerJobId",
    };
};

pub const GetTransformerJobOutput = struct {
    /// Returns an optional error message, which gets populated when the job is not
    /// run successfully.
    message: ?[]const u8 = null,

    /// Returns the location for the output files. If the caller specified a
    /// directory for the output, then this contains the full path to the output
    /// file, including the file name generated by the service.
    output_files: ?[]const S3Location = null,

    /// Returns the current state of the transformer job, either `running`,
    /// `succeeded`, or `failed`.
    status: TransformerJobStatus,

    pub const json_field_names = .{
        .message = "message",
        .output_files = "outputFiles",
        .status = "status",
    };
};

pub fn execute(client: *Client, allocator: std.mem.Allocator, input: GetTransformerJobInput, options: CallOptions) !GetTransformerJobOutput {
    var arena = std.heap.ArenaAllocator.init(client.allocator);
    defer arena.deinit();
    const alloc = arena.allocator();

    var request = try serializeRequest(alloc, input, client.config);
    defer request.deinit(alloc);

    const creds = try client.config.credentials.getCredentials(client.allocator);
    try aws.signing.signRequest(alloc, client.config.io, &request, creds, client.config.region, "b2bi", client.config.http_client.clock_skew_offset);

    var response = try client.config.http_client.sendRequestWithOptions(&request, client.options);
    defer response.deinit();

    if (!response.isSuccess()) {
        if (options.diagnostic) |d| {
            d.* = try parseErrorResponse(client.allocator, response.body, response.status);
        }
        return error.ServiceError;
    }

    const result = try deserializeResponse(allocator, response.body, response.status, response.headers);
    return result;
}

fn serializeRequest(allocator: std.mem.Allocator, input: GetTransformerJobInput, config: *aws.Config) !aws.http.Request {
    const endpoint = try config.getEndpointForService("b2bi", "b2bi", allocator);

    const ep = try aws.url.parseEndpoint(endpoint);

    const body = try aws.json.jsonStringify(input, allocator);

    var request = aws.http.Request.init(ep.host);
    request.method = .POST;
    request.path = "/";
    request.tls = ep.tls;
    request.port = ep.port;
    request.body = body;
    try request.headers.put(allocator, "Content-Type", "application/x-amz-json-1.0");
    try request.headers.put(allocator, "X-Amz-Target", "B2BI.GetTransformerJob");

    return request;
}

fn deserializeResponse(allocator: std.mem.Allocator, body: []const u8, status: u16, headers: anytype) !GetTransformerJobOutput {
    _ = status;
    _ = headers;
    return aws.json.parseJsonObject(GetTransformerJobOutput, body, allocator);
}
