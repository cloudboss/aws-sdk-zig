const aws = @import("aws");
const std = @import("std");

const Client = @import("client.zig").Client;
const CallOptions = @import("call_options.zig").CallOptions;
const parseErrorResponse = @import("errors.zig").parseErrorResponse;
const MajorKeyDerivationMode = @import("major_key_derivation_mode.zig").MajorKeyDerivationMode;
const SessionKeyDerivation = @import("session_key_derivation.zig").SessionKeyDerivation;

pub const GenerateAuthRequestCryptogramInput = struct {
    /// The `keyARN` of the IMK-AC (TR31_E0_EMV_MKEY_APP_CRYPTOGRAMS) that Amazon
    /// Web Services Payment Cryptography uses to generate the ARQC.
    key_identifier: []const u8,

    /// The method to use when deriving the major encryption key for ARQC generation
    /// within Amazon Web Services Payment Cryptography.
    major_key_derivation_mode: MajorKeyDerivationMode,

    /// The attributes and values to use for deriving a session key for ARQC
    /// generation within Amazon Web Services Payment Cryptography.
    session_key_derivation_attributes: SessionKeyDerivation,

    /// The transaction data that Amazon Web Services Payment Cryptography uses for
    /// ARQC generation. The same transaction data is used for ARQC verification by
    /// the issuer using VerifyAuthRequestCryptogram.
    transaction_data: []const u8,

    pub const json_field_names = .{
        .key_identifier = "KeyIdentifier",
        .major_key_derivation_mode = "MajorKeyDerivationMode",
        .session_key_derivation_attributes = "SessionKeyDerivationAttributes",
        .transaction_data = "TransactionData",
    };
};

pub const GenerateAuthRequestCryptogramOutput = struct {
    /// The Authorization Request Cryptogram (ARQC) generated by Amazon Web Services
    /// Payment Cryptography using the specified key and transaction data.
    auth_request_cryptogram: []const u8,

    /// The `keyARN` of the IMK-AC that Amazon Web Services Payment Cryptography
    /// uses for ARQC generation.
    key_arn: []const u8,

    /// The key check value (KCV) of the encryption key. The KCV is used to check if
    /// all parties holding a given key have the same key or to detect that a key
    /// has changed.
    ///
    /// Amazon Web Services Payment Cryptography computes the KCV according to the
    /// CMAC specification.
    key_check_value: []const u8,

    pub const json_field_names = .{
        .auth_request_cryptogram = "AuthRequestCryptogram",
        .key_arn = "KeyArn",
        .key_check_value = "KeyCheckValue",
    };
};

pub fn execute(client: *Client, allocator: std.mem.Allocator, input: GenerateAuthRequestCryptogramInput, options: CallOptions) !GenerateAuthRequestCryptogramOutput {
    var arena = std.heap.ArenaAllocator.init(client.allocator);
    defer arena.deinit();
    const alloc = arena.allocator();

    var request = try serializeRequest(alloc, input, client.config);
    defer request.deinit(alloc);

    const creds = try client.config.credentials.getCredentials(client.allocator);
    try aws.signing.signRequest(alloc, client.config.io, &request, creds, client.config.region, "paymentcryptographydataplane", client.config.http_client.clock_skew_offset);

    var response = try client.config.http_client.sendRequestWithOptions(&request, client.options);
    defer response.deinit();

    if (!response.isSuccess()) {
        if (options.diagnostic) |d| {
            d.* = try parseErrorResponse(client.allocator, response.body, response.status);
        }
        return error.ServiceError;
    }

    const result = try deserializeResponse(allocator, response.body, response.status, response.headers);
    return result;
}

fn serializeRequest(allocator: std.mem.Allocator, input: GenerateAuthRequestCryptogramInput, config: *aws.Config) !aws.http.Request {
    const endpoint = try config.getEndpointForService("dataplane.payment-cryptography", "Payment Cryptography Data", allocator);

    const ep = try aws.url.parseEndpoint(endpoint);

    const path = "/cryptogram/generate";

    var body_buf: std.ArrayList(u8) = .empty;
    var has_prev = false;
    try body_buf.appendSlice(allocator, "{");

    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"KeyIdentifier\":");
    try aws.json.writeValue(@TypeOf(input.key_identifier), input.key_identifier, allocator, &body_buf);
    has_prev = true;
    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"MajorKeyDerivationMode\":");
    try aws.json.writeValue(@TypeOf(input.major_key_derivation_mode), input.major_key_derivation_mode, allocator, &body_buf);
    has_prev = true;
    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"SessionKeyDerivationAttributes\":");
    try aws.json.writeValue(@TypeOf(input.session_key_derivation_attributes), input.session_key_derivation_attributes, allocator, &body_buf);
    has_prev = true;
    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"TransactionData\":");
    try aws.json.writeValue(@TypeOf(input.transaction_data), input.transaction_data, allocator, &body_buf);
    has_prev = true;

    try body_buf.appendSlice(allocator, "}");
    const body = try body_buf.toOwnedSlice(allocator);

    var request = aws.http.Request.init(ep.host);
    request.method = .POST;
    request.path = path;
    request.tls = ep.tls;
    request.port = ep.port;
    request.body = body;
    try request.headers.put(allocator, "Content-Type", "application/json");

    return request;
}

fn deserializeResponse(allocator: std.mem.Allocator, body: []const u8, status: u16, headers: anytype) !GenerateAuthRequestCryptogramOutput {
    const result: GenerateAuthRequestCryptogramOutput = try aws.json.parseJsonObject(
        GenerateAuthRequestCryptogramOutput,
        if (body.len > 0) body else "{}",
        allocator,
    );
    _ = status;
    _ = headers;

    return result;
}
