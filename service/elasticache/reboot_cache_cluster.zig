const aws = @import("aws");
const std = @import("std");

const Client = @import("client.zig").Client;
const CallOptions = @import("call_options.zig").CallOptions;
const parseErrorResponse = @import("errors.zig").parseErrorResponse;
const CacheCluster = @import("cache_cluster.zig").CacheCluster;
const serde = @import("serde.zig");

pub const RebootCacheClusterInput = struct {
    /// The cluster identifier. This parameter is stored as a lowercase string.
    cache_cluster_id: []const u8,

    /// A list of cache node IDs to reboot. A node ID is a numeric identifier (0001,
    /// 0002,
    /// etc.). To reboot an entire cluster, specify all of the cache node IDs.
    cache_node_ids_to_reboot: []const []const u8,
};

pub const RebootCacheClusterOutput = struct {
    cache_cluster: ?CacheCluster = null,
};

pub fn execute(client: *Client, allocator: std.mem.Allocator, input: RebootCacheClusterInput, options: CallOptions) !RebootCacheClusterOutput {
    var arena = std.heap.ArenaAllocator.init(client.allocator);
    defer arena.deinit();
    const alloc = arena.allocator();

    var request = try serializeRequest(alloc, input, client.config);
    defer request.deinit(alloc);

    const creds = try client.config.credentials.getCredentials(client.allocator);
    try aws.signing.signRequest(alloc, client.config.io, &request, creds, client.config.region, "elasticache", client.config.http_client.clock_skew_offset);

    var response = try client.config.http_client.sendRequestWithOptions(&request, client.options);
    defer response.deinit();

    if (!response.isSuccess()) {
        if (options.diagnostic) |d| {
            d.* = try parseErrorResponse(client.allocator, response.body, response.status);
        }
        return error.ServiceError;
    }

    const result = try deserializeResponse(allocator, response.body, response.status, response.headers);
    return result;
}

fn serializeRequest(allocator: std.mem.Allocator, input: RebootCacheClusterInput, config: *aws.Config) !aws.http.Request {
    const endpoint = try config.getEndpointForService("elasticache", "ElastiCache", allocator);

    const ep = try aws.url.parseEndpoint(endpoint);

    var body_buf: std.ArrayList(u8) = .empty;

    try body_buf.appendSlice(allocator, "Action=RebootCacheCluster&Version=2015-02-02");
    try body_buf.appendSlice(allocator, "&CacheClusterId=");
    try aws.url.appendUrlEncoded(allocator, &body_buf, input.cache_cluster_id);
    for (input.cache_node_ids_to_reboot, 0..) |item, idx| {
        const n = idx + 1;
        var prefix_buf: [256]u8 = undefined;
        const field_prefix = std.fmt.bufPrint(&prefix_buf, "&CacheNodeIdsToReboot.CacheNodeId.{d}=", .{n}) catch continue;
        try body_buf.appendSlice(allocator, field_prefix);
        try aws.url.appendUrlEncoded(allocator, &body_buf, item);
    }

    const body = try body_buf.toOwnedSlice(allocator);

    var request = aws.http.Request.init(ep.host);
    request.method = .POST;
    request.path = "/";
    request.tls = ep.tls;
    request.port = ep.port;
    request.body = body;
    try request.headers.put(allocator, "Content-Type", "application/x-www-form-urlencoded");

    return request;
}

fn deserializeResponse(allocator: std.mem.Allocator, body: []const u8, status: u16, headers: anytype) !RebootCacheClusterOutput {
    _ = status;
    _ = headers;
    var reader = aws.xml.Reader.init(body);

    while (try reader.next()) |event| {
        switch (event) {
            .element_start => |e| {
                if (std.mem.eql(u8, e.local, "RebootCacheClusterResult")) break;
            },
            else => {},
        }
    }

    var result: RebootCacheClusterOutput = .{};
    while (try reader.next()) |event| {
        switch (event) {
            .element_start => |e| {
                if (std.mem.eql(u8, e.local, "CacheCluster")) {
                    result.cache_cluster = try serde.deserializeCacheCluster(allocator, &reader);
                } else {
                    try reader.skipElement();
                }
            },
            .element_end => break,
            else => {},
        }
    }

    return result;
}
