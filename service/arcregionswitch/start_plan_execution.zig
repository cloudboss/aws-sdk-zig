const ExecutionAction = @import("execution_action.zig").ExecutionAction;
const ExecutionMode = @import("execution_mode.zig").ExecutionMode;

pub const StartPlanExecutionInput = struct {
    /// The action to perform. Valid values are `activate` (to shift traffic to the
    /// target Region) or `deactivate` (to shift traffic away from the target
    /// Region).
    action: ExecutionAction,

    /// An optional comment explaining why the plan execution is being started.
    comment: ?[]const u8 = null,

    /// A boolean value indicating whether to use the latest version of the plan. If
    /// set to false, you must specify a specific version.
    latest_version: ?[]const u8 = null,

    /// The plan execution mode. Valid values are `graceful`, for starting the
    /// execution in graceful mode, or `ungraceful`, for starting the execution in
    /// ungraceful mode.
    mode: ?ExecutionMode = null,

    /// The Amazon Resource Name (ARN) of the plan to execute.
    plan_arn: []const u8,

    /// The execution identifier of the recovery execution that ran in the opposite
    /// region post-recovery is ran in. Required when starting a post-recovery
    /// execution.
    recovery_execution_id: ?[]const u8 = null,

    /// The Amazon Web Services Region to target with this execution. This is the
    /// Region that traffic will be shifted to or from, depending on the action.
    target_region: []const u8,

    pub const json_field_names = .{
        .action = "action",
        .comment = "comment",
        .latest_version = "latestVersion",
        .mode = "mode",
        .plan_arn = "planArn",
        .recovery_execution_id = "recoveryExecutionId",
        .target_region = "targetRegion",
    };
};

