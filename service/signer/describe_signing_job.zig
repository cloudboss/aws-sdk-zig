    platform_display_name: ?[]const u8 = null,

    /// The microcontroller platform to which your signed code image will be
    /// distributed.
    platform_id: ?[]const u8 = null,

    /// The name of the profile that initiated the signing operation.
    profile_name: ?[]const u8 = null,

    /// The version of the signing profile used to initiate the signing job.
    profile_version: ?[]const u8 = null,

    /// The IAM principal that requested the signing job.
    requested_by: ?[]const u8 = null,

    /// A revocation record if the signature generated by the signing job has been
    /// revoked.
    /// Contains a timestamp and the ID of the IAM entity that revoked the
    /// signature.
    revocation_record: ?SigningJobRevocationRecord = null,

    /// Thr expiration timestamp for the signature generated by the signing job.
    signature_expires_at: ?i64 = null,

    /// Name of the S3 bucket where the signed code image is saved by AWS Signer.
    signed_object: ?SignedObject = null,

    /// The Amazon Resource Name (ARN) of your code signing certificate.
