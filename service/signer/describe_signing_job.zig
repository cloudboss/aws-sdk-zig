        .revocation_record = "revocationRecord",
        .signature_expires_at = "signatureExpiresAt",
        .signed_object = "signedObject",
        .signing_material = "signingMaterial",
        .signing_parameters = "signingParameters",
        .source = "source",
        .status = "status",
        .status_reason = "statusReason",
    };
