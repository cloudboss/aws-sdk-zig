const RecommendationResultConfigurationBundle = @import("recommendation_result_configuration_bundle.zig").RecommendationResultConfigurationBundle;

/// The result of a system prompt recommendation, containing the optimized
/// prompt.
pub const SystemPromptRecommendationResult = struct {
    /// The configuration bundle containing the recommended system prompt, if the
    /// input was sourced from a configuration bundle.
    configuration_bundle: ?RecommendationResultConfigurationBundle = null,

    /// The error code if the recommendation failed.
    error_code: ?[]const u8 = null,

    /// The error message if the recommendation failed.
    error_message: ?[]const u8 = null,

    /// The optimized system prompt text generated by the recommendation.
    recommended_system_prompt: ?[]const u8 = null,

    pub const json_field_names = .{
        .configuration_bundle = "configurationBundle",
        .error_code = "errorCode",
        .error_message = "errorMessage",
        .recommended_system_prompt = "recommendedSystemPrompt",
    };
};
