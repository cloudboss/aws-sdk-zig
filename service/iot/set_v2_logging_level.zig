const aws = @import("aws");
const std = @import("std");

const Client = @import("client.zig").Client;
const CallOptions = @import("call_options.zig").CallOptions;
const parseErrorResponse = @import("errors.zig").parseErrorResponse;
const LogLevel = @import("log_level.zig").LogLevel;
const LogTarget = @import("log_target.zig").LogTarget;

pub const SetV2LoggingLevelInput = struct {
    /// The log level.
    log_level: LogLevel,

    /// The log target.
    log_target: LogTarget,

    pub const json_field_names = .{
        .log_level = "logLevel",
        .log_target = "logTarget",
    };
};

pub const SetV2LoggingLevelOutput = struct {};

pub fn execute(client: *Client, allocator: std.mem.Allocator, input: SetV2LoggingLevelInput, options: CallOptions) !SetV2LoggingLevelOutput {
    var arena = std.heap.ArenaAllocator.init(client.allocator);
    defer arena.deinit();
    const alloc = arena.allocator();

    var request = try serializeRequest(alloc, input, client.config);
    defer request.deinit(alloc);

    const creds = try client.config.credentials.getCredentials(client.allocator);
    try aws.signing.signRequest(alloc, client.config.io, &request, creds, client.config.region, "iot", client.config.http_client.clock_skew_offset);

    var response = try client.config.http_client.sendRequestWithOptions(&request, client.options);
    defer response.deinit();

    if (!response.isSuccess()) {
        if (options.diagnostic) |d| {
            d.* = try parseErrorResponse(client.allocator, response.body, response.status);
        }
        return error.ServiceError;
    }

    const result = try deserializeResponse(allocator, response.body, response.status, response.headers);
    return result;
}

fn serializeRequest(allocator: std.mem.Allocator, input: SetV2LoggingLevelInput, config: *aws.Config) !aws.http.Request {
    const endpoint = try config.getEndpointForService("iot", "IoT", allocator);

    const ep = try aws.url.parseEndpoint(endpoint);

    const path = "/v2LoggingLevel";

    var body_buf: std.ArrayList(u8) = .empty;
    var has_prev = false;
    try body_buf.appendSlice(allocator, "{");

    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"logLevel\":");
    try aws.json.writeValue(@TypeOf(input.log_level), input.log_level, allocator, &body_buf);
    has_prev = true;
    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"logTarget\":");
    try aws.json.writeValue(@TypeOf(input.log_target), input.log_target, allocator, &body_buf);
    has_prev = true;

    try body_buf.appendSlice(allocator, "}");
    const body = try body_buf.toOwnedSlice(allocator);

    var request = aws.http.Request.init(ep.host);
    request.method = .POST;
    request.path = path;
    request.tls = ep.tls;
    request.port = ep.port;
    request.body = body;
    try request.headers.put(allocator, "Content-Type", "application/json");

    return request;
}

fn deserializeResponse(allocator: std.mem.Allocator, body: []const u8, status: u16, headers: anytype) !SetV2LoggingLevelOutput {
    _ = allocator;
    _ = body;
    _ = status;
    _ = headers;
    const result: SetV2LoggingLevelOutput = .{};

    return result;
}
