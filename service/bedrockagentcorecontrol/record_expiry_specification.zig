const RecordExpiryAction = @import("record_expiry_action.zig").RecordExpiryAction;

/// Specifies the record expiry (long-term memory time-to-live) for a memory
/// strategy. Provide exactly one of `recordExpiryDurationDays` or `action`. Set
/// `recordExpiryDurationDays` to configure or update the time-to-live, or set
/// `action` to `REMOVE` to remove a previously configured time-to-live.
pub const RecordExpirySpecification = union(enum) {
    /// The action to apply to the existing record expiry (long-term memory
    /// time-to-live) configuration. Set to `REMOVE` to remove a previously
    /// configured time-to-live so that newer records no longer expire. This value
    /// is not applicable on create paths.
    action: ?RecordExpiryAction,
    /// The duration, in days, after which memory records generated by this strategy
    /// expire. The minimum is 31 days.
    record_expiry_duration_days: ?i32,

    pub const json_field_names = .{
        .action = "action",
        .record_expiry_duration_days = "recordExpiryDurationDays",
    };
};
