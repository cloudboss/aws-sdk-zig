const MemoryRecordSchema = @import("memory_record_schema.zig").MemoryRecordSchema;
const RecordExpirySpecification = @import("record_expiry_specification.zig").RecordExpirySpecification;

/// Input for creating a semantic memory strategy.
pub const SemanticMemoryStrategyInput = struct {
    /// The description of the semantic memory strategy.
    description: ?[]const u8 = null,

    memory_record_schema: ?MemoryRecordSchema = null,

    /// The name of the semantic memory strategy.
    name: []const u8,

    /// This is a legacy parameter, use `namespaceTemplates`. The namespaces
    /// associated with the semantic memory strategy.
    namespaces: ?[]const []const u8 = null,

    /// The namespaceTemplates associated with the semantic memory strategy.
    namespace_templates: ?[]const []const u8 = null,

    /// The record expiry (long-term memory time-to-live) configuration for memory
    /// records generated by this strategy. Set `recordExpiryDurationDays` to the
    /// number of days after which records expire. If not specified, records
    /// generated by this strategy do not expire.
    record_expiry_specification: ?RecordExpirySpecification = null,

    pub const json_field_names = .{
        .description = "description",
        .memory_record_schema = "memoryRecordSchema",
        .name = "name",
        .namespaces = "namespaces",
        .namespace_templates = "namespaceTemplates",
        .record_expiry_specification = "recordExpirySpecification",
    };
};
