fn serializeRequest(allocator: std.mem.Allocator, input: GetAccessKeyInfoInput, config: *aws.Config) !aws.http.Request {
    const endpoint = try config.getEndpointForService("sts", "STS", allocator);

    const ep = try aws.url.parseEndpoint(endpoint);

    var body_buf: std.ArrayList(u8) = .empty;

    try body_buf.appendSlice(allocator, "Action=GetAccessKeyInfo&Version=2011-06-15");
    try body_buf.appendSlice(allocator, "&AccessKeyId=");
    try aws.url.appendUrlEncoded(allocator, &body_buf, input.access_key_id);

    const body = try body_buf.toOwnedSlice(allocator);

    var request = aws.http.Request.init(ep.host);
    request.method = .POST;
    request.path = "/";
    request.tls = ep.tls;
    request.port = ep.port;
    request.body = body;
    try request.headers.put(allocator, "Content-Type", "application/x-www-form-urlencoded");

    return request;
}

