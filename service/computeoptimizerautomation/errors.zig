        if (parsed_error) |parsed| {
            var typed_error = parsed;
            typed_error.message = owned_message;
            typed_error.request_id = owned_request_id;
            return .{ .arena = arena, .kind = .{ .not_management_account_exception = typed_error } };
        }
    }
    if (std.mem.eql(u8, error_code, "OptInRequiredException")) {
        const parsed_error: ?OptInRequiredException = aws.json.parseJsonObject(OptInRequiredException, body, arena_alloc) catch |err| switch (err) {
            error.OutOfMemory => return error.OutOfMemory,
            else => null,
        };
        if (parsed_error) |parsed| {
            var typed_error = parsed;
            typed_error.message = owned_message;
            typed_error.request_id = owned_request_id;
