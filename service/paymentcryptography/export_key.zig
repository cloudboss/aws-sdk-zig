        }
    }
    if (std.mem.eql(u8, error_code, "PublicPolicyException")) {
        const parsed_error: ?errors.PublicPolicyException = aws.json.parseJsonObject(errors.PublicPolicyException, body, arena_alloc) catch |err| switch (err) {
