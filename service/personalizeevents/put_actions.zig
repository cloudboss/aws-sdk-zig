const aws = @import("aws");
const std = @import("std");

const Client = @import("client.zig").Client;
const CallOptions = @import("call_options.zig").CallOptions;
const parseErrorResponse = @import("errors.zig").parseErrorResponse;
const Action = @import("action.zig").Action;

pub const PutActionsInput = struct {
    /// A list of action data.
    actions: []const Action,

    /// The Amazon Resource Name (ARN) of the Actions dataset you are adding the
    /// action or actions to.
    dataset_arn: []const u8,

    pub const json_field_names = .{
        .actions = "actions",
        .dataset_arn = "datasetArn",
    };
};

pub const PutActionsOutput = struct {};

pub fn execute(client: *Client, allocator: std.mem.Allocator, input: PutActionsInput, options: CallOptions) !PutActionsOutput {
    var arena = std.heap.ArenaAllocator.init(client.allocator);
    defer arena.deinit();
    const alloc = arena.allocator();

    var request = try serializeRequest(alloc, input, client.config);
    defer request.deinit(alloc);

    const creds = try client.config.credentials.getCredentials(client.allocator);
    try aws.signing.signRequest(alloc, client.config.io, &request, creds, client.config.region, "personalize", client.config.http_client.clock_skew_offset);

    var response = try client.config.http_client.sendRequestWithOptions(&request, client.options);
    defer response.deinit();

    if (!response.isSuccess()) {
        if (options.diagnostic) |d| {
            d.* = try parseErrorResponse(client.allocator, response.body, response.status);
        }
        return error.ServiceError;
    }

    const result = try deserializeResponse(allocator, response.body, response.status, response.headers);
    return result;
}

fn serializeRequest(allocator: std.mem.Allocator, input: PutActionsInput, config: *aws.Config) !aws.http.Request {
    const endpoint = try config.getEndpointForService("personalize-events", "Personalize Events", allocator);

    const ep = try aws.url.parseEndpoint(endpoint);

    const path = "/actions";

    var body_buf: std.ArrayList(u8) = .empty;
    var has_prev = false;
    try body_buf.appendSlice(allocator, "{");

    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"actions\":");
    try aws.json.writeValue(@TypeOf(input.actions), input.actions, allocator, &body_buf);
    has_prev = true;
    if (has_prev) try body_buf.appendSlice(allocator, ",");
    try body_buf.appendSlice(allocator, "\"datasetArn\":");
    try aws.json.writeValue(@TypeOf(input.dataset_arn), input.dataset_arn, allocator, &body_buf);
    has_prev = true;

    try body_buf.appendSlice(allocator, "}");
    const body = try body_buf.toOwnedSlice(allocator);

    var request = aws.http.Request.init(ep.host);
    request.method = .POST;
    request.path = path;
    request.tls = ep.tls;
    request.port = ep.port;
    request.body = body;
    try request.headers.put(allocator, "Content-Type", "application/json");

    return request;
}

fn deserializeResponse(allocator: std.mem.Allocator, body: []const u8, status: u16, headers: anytype) !PutActionsOutput {
    _ = allocator;
    _ = body;
    _ = status;
    _ = headers;
    const result: PutActionsOutput = .{};

    return result;
}
